        sb.AppendLine($"{indent}        }}");
        sb.AppendLine($"{indent}    }}");
        sb.AppendLine($"{indent}}}");
        sb.AppendLine();
    }

    private static bool IsAttributeGroup(IPropertySymbol member)
    {
        if (member.Type is not INamedTypeSymbol namedType)
            return false;

        if (namedType.TypeKind != TypeKind.Class)
            return false;

        if (IsStreamType(namedType)) return false;
        var unwrapped = GetUnwrappedType(namedType);
        if (unwrapped.SpecialType != SpecialType.None) return false;
        if (unwrapped.TypeKind == TypeKind.Enum) return false;
        if (unwrapped.AllInterfaces.Any(i => i.Name == "ISmartEnum")) return false;
        if (unwrapped.Name is "Uri" or "IppVersion" or "DateTimeOffset" or "String" or "Int32" or "Boolean" or "Stream") return false;

        return GetAllProperties(namedType).Count > 0;
    }

    private static (string PropPrefix, string CliPrefix, string SectionTitle, string JsonCliOption) GetAttributeGroupInfo(string containerName)
    {
        string acronym;
        if (containerName.Equals("OperationAttributes", StringComparison.OrdinalIgnoreCase))
        {
            acronym = "op";
        }
        else
        {
            var matches = Regex.Matches(containerName, @"[A-Z][a-z0-9]*");
            var sb = new StringBuilder();
            foreach (Match match in matches)
            {
                if (match.Value.Length > 0)
                {
                    sb.Append(char.ToLowerInvariant(match.Value[0]));
                }
            }
            acronym = sb.Length > 0 ? sb.ToString() : containerName.ToLowerInvariant();
        }

        var propPrefix = char.ToUpperInvariant(acronym[0]) + (acronym.Length > 1 ? acronym.Substring(1) : "");
        var cliPrefix = $"--{acronym}-";
        var sectionTitle = ToSectionTitle(containerName);
        var jsonCliOption = $"--{acronym} <JSON>";

        return (propPrefix, cliPrefix, sectionTitle, jsonCliOption);
    }

    private static string ToSectionTitle(string value)
    {
        if (string.IsNullOrEmpty(value)) return value;
        return Regex.Replace(value, "([a-z])([A-Z])", "$1 $2");
    }

    private static bool IsIppCollection(ITypeSymbol type)
    {
        var unwrapped = GetUnwrappedType(type);
        return unwrapped.AllInterfaces.Any(i => i.Name == "IIppCollection");
    }

    private static void GenerateRangeProperty(
        StringBuilder sb,
        string indent,
